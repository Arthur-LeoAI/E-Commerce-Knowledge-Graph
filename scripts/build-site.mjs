// Builds the static site into dist/ from data/, rules/, models/ and site/.
// dist/atlas-data.js exposes the content as globals in the shapes the ported
// prototype code expects (Chinese base objects plus *_EN counterparts).
import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

const ROOT = path.resolve(import.meta.dirname, '..');
const DIST = path.join(ROOT, 'dist');
const load = (rel) => yaml.load(fs.readFileSync(path.join(ROOT, rel), 'utf8'), { schema: yaml.JSON_SCHEMA });
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
  const p = path.join(dir, d.name);
  return d.isDirectory() ? walk(p) : p.endsWith('.yaml') ? [p] : [];
});

const domains = load('data/domains.yaml');
const letter = Object.fromEntries(domains.map((d) => [d.id, d.letter]));
const nodes = walk(path.join(ROOT, 'data', 'nodes'))
  .map((f) => yaml.load(fs.readFileSync(f, 'utf8'), { schema: yaml.JSON_SCHEMA }))
  .sort((a, b) => a.order - b.order);
const edges = load('data/edges.yaml');
const phases = load('data/phases.yaml');
const tour = load('data/tour.yaml');
const glossary = load('data/glossary.yaml');
const tools = load('data/tools.yaml');
const ui = load('data/ui.yaml');
const pages = load('data/pages.yaml');
const exampleCase = load('data/example-case.yaml');
const rules = walk(path.join(ROOT, 'rules'))
  .map((f) => yaml.load(fs.readFileSync(f, 'utf8'), { schema: yaml.JSON_SCHEMA }))
  .sort((a, b) => a.id.localeCompare(b.id));

const gloss = (lang) => Object.fromEntries(glossary.flatMap((g) =>
  [g.term[lang], ...(g.aliases?.[lang] ?? [])].map((t) => [t, g.def[lang]])));

const out = {
  DOMAINS: domains.map((d) => ({ k: d.letter, code: d.code, c: d.colour, name: d.name.zh, desc: d.desc.zh })),
  DOMAINS_EN: Object.fromEntries(domains.map((d) => [d.letter, { name: d.name.en, desc: d.desc.en }])),
  NODES: nodes.map((n) => ({ id: n.id, d: letter[n.domain], n: n.name.zh, en: n.name.en, what: n.what.zh,
    how: n.how.zh, m: n.metrics.zh, data: n.data_later.zh, rules: n.rules })),
  NODES_EN: Object.fromEntries(nodes.map((n) => [n.id, { n: n.name.en, what: n.what.en, how: n.how.en,
    m: n.metrics.en, data: n.data_later.en }])),
  EDGES: edges.map((e) => [e.from, e.to, e.label.zh]),
  EDGE_EN_LIST: edges.map((e) => e.label.en),
  EX: Object.fromEntries(nodes.map((n) => [n.id, n.example.zh])),
  EX_EN: Object.fromEntries(nodes.map((n) => [n.id, n.example.en])),
  PHASES: phases.map((p) => ({ t: p.title.zh, out: p.output.zh, warn: p.warning.zh, ids: p.nodes })),
  PHASES_EN: phases.map((p) => ({ t: p.title.en, out: p.output.en, warn: p.warning.en })),
  TOUR: tour.map((t) => ({ d: letter[t.domain], title: t.title?.zh ?? '', node: t.node, one: t.one_line.zh, ex: t.body_html.zh })),
  TOUR_EN: tour.map((t) => ({ title: t.title?.en ?? '', one: t.one_line.en, ex: t.body_html.en })),
  GLOSS: gloss('zh'),
  GLOSS_EN: gloss('en'),
  TOOLS: tools.map((t) => ({ t: t.name.zh, u: t.url })),
  TOOLS_EN: tools.map((t) => t.name.en),
  UI: {
    zh: Object.fromEntries(Object.entries(ui).map(([k, v]) => [k, v.zh])),
    en: Object.fromEntries(Object.entries(ui).map(([k, v]) => [k, v.en])),
  },
  PAGES: pages,
  RULES: rules,
  CASE: exampleCase,
};

fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(DIST, { recursive: true });
const header = '// Generated by scripts/build-site.mjs from data/ and rules/. Do not edit. Licensed under Apache-2.0.\n';
fs.writeFileSync(path.join(DIST, 'atlas-data.js'),
  header + Object.entries(out).map(([k, v]) => `const ${k} = ${JSON.stringify(v)};`).join('\n') + '\n');
for (const [from, to] of [['site/index.html', 'index.html'], ['site/app.js', 'app.js'], ['models/calculators.js', 'calculators.js']]) {
  fs.copyFileSync(path.join(ROOT, from), path.join(DIST, to));
}
fs.writeFileSync(path.join(DIST, '.nojekyll'), '');
console.log(`Built dist/: ${nodes.length} nodes, ${edges.length} edges, ${rules.length} rules, ${Object.keys(ui).length} UI strings.`);
